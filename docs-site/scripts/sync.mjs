/**
 * Snapshot vault PRDs + git law/ops into Starlight content.
 * Generated trees: src/content/docs/{prd,law,product,ops}/
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SITE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REPO_ROOT = path.resolve(SITE_ROOT, "..");
const DOCS_SRC = path.join(SITE_ROOT, "src", "content", "docs");

const GENERATED_BANNER = `> Generated snapshot. **Do not edit this file.** Change the source, then \`npm run docs:sync\`.
`;

function rimrafGenerated(relDir) {
  const abs = path.join(DOCS_SRC, relDir);
  if (fs.existsSync(abs)) fs.rmSync(abs, { recursive: true, force: true });
  fs.mkdirSync(abs, { recursive: true });
}

function slugify(name) {
  return name
    .replace(/\.md$/i, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function parseFrontmatter(raw) {
  if (!raw.startsWith("---")) return { fm: {}, body: raw };
  const end = raw.indexOf("\n---", 3);
  if (end < 0) return { fm: {}, body: raw };
  const yaml = raw.slice(4, end);
  const body = raw.slice(end + 4).replace(/^\r?\n/, "");
  /** @type {Record<string, string>} */
  const fm = {};
  for (const line of yaml.split(/\r?\n/)) {
    const m = line.match(/^([A-Za-z0-9_]+):\s*(.*)$/);
    if (!m) continue;
    let v = m[2].trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
      v = v.slice(1, -1);
    }
    fm[m[1]] = v;
  }
  return { fm, body };
}

function wikilinksToMd(text) {
  return text.replace(/\[\[([^\]|#]+)(?:#[^\]|]+)?(?:\|([^\]]+))?\]\]/g, (_, target, alias) => {
    const label = (alias || target).trim();
    const slug = slugify(target.trim());
    return `[${label}](/prd/${slug}/)`;
  });
}

function starlightPage({ title, description, extra = [], body, source }) {
  const desc = (description || title).replace(/"/g, "'").slice(0, 220);
  const lines = [
    "---",
    `title: ${JSON.stringify(title)}`,
    `description: ${JSON.stringify(desc)}`,
    ...extra,
    "---",
    "",
    GENERATED_BANNER,
    "",
    `_Source: \`${source}\`_`,
    "",
    body.trim(),
    "",
  ];
  return lines.join("\n");
}

function writeGenerated(relPath, contents) {
  const abs = path.join(DOCS_SRC, relPath);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, contents, "utf8");
}

function copyLaw() {
  rimrafGenerated("law");
  const files = [
    ["domain-business-rules.md", "Domain business rules (DBR)"],
    ["domain-acceptance-criteria.md", "Domain acceptance criteria (DAC)"],
    ["business-rules.md", "Feature business rules (BR)"],
  ];
  for (const [name, title] of files) {
    const src = path.join(REPO_ROOT, "specs", name);
    if (!fs.existsSync(src)) continue;
    const raw = fs.readFileSync(src, "utf8");
    const { body } = parseFrontmatter(raw);
    writeGenerated(
      `law/${name}`,
      starlightPage({
        title,
        description: title,
        body,
        source: `specs/${name}`,
      }),
    );
  }
  writeGenerated(
    "law/index.md",
    starlightPage({
      title: "Domain law",
      description: "Enforceable DBR, DAC, and BR wording.",
      extra: ["template: doc"],
      body: [
        "| Pack | Page |",
        "| --- | --- |",
        "| DBR | [Domain business rules](/law/domain-business-rules/) |",
        "| DAC | [Domain acceptance criteria](/law/domain-acceptance-criteria/) |",
        "| BR | [Feature business rules](/law/business-rules/) |",
        "",
        "IDs stay in git. Product-map attaches IDs; it does not own wording.",
      ].join("\n"),
      source: "specs/",
    }),
  );
}

function copyProduct() {
  rimrafGenerated("product");
  const src = path.join(REPO_ROOT, "PRODUCT.md");
  if (!fs.existsSync(src)) return;
  const raw = fs.readFileSync(src, "utf8");
  const { body } = parseFrontmatter(raw);
  writeGenerated(
    "product/product.md",
    starlightPage({
      title: "Product (framing)",
      description: "Purpose, positioning, capabilities, constraints.",
      body,
      source: "PRODUCT.md",
    }),
  );
}

function copyOps() {
  rimrafGenerated("ops");
  const files = [
    ["docs/README.md", "ops/docs-map.md", "Repo docs map"],
    ["docs/architecture/README.md", "ops/architecture.md", "Architecture / port ops"],
    ["specs/README.md", "ops/specs-index.md", "Specs live vs archive"],
  ];
  for (const [from, to, title] of files) {
    const src = path.join(REPO_ROOT, from);
    if (!fs.existsSync(src)) continue;
    const raw = fs.readFileSync(src, "utf8");
    const { body } = parseFrontmatter(raw);
    writeGenerated(
      to,
      starlightPage({
        title,
        description: title,
        body,
        source: from,
      }),
    );
  }
}

function findVaultProjectDir() {
  const candidates = [
    path.join(REPO_ROOT, "requirements", "Projects", "Destiny 2 Build Creator"),
    path.join(
      process.env.USERPROFILE || "",
      "SyncThing",
      "Obsidian",
      "ProjectTracker",
      "Projects",
      "Destiny 2 Build Creator",
    ),
  ];
  return candidates.find((p) => p && fs.existsSync(p)) || null;
}

function walkMd(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) {
      if (ent.name.startsWith(".")) continue;
      walkMd(p, acc);
    } else if (ent.isFile() && ent.name.endsWith(".md") && !ent.name.includes("Template")) {
      acc.push(p);
    }
  }
  return acc;
}

function copyPrds() {
  const outDir = path.join(DOCS_SRC, "prd");
  const vault = findVaultProjectDir();
  if (!vault) {
    fs.mkdirSync(outDir, { recursive: true });
    if (!fs.existsSync(path.join(outDir, "index.md"))) {
      writeGenerated(
        "prd/index.md",
        starlightPage({
          title: "PRDs",
          description: "Obsidian product notes.",
          body: "Vault junction not mounted. Run `pwsh -File scripts/link-projecttracker-requirements.ps1` and `npm run docs:sync`.",
          source: "requirements/ (missing)",
        }),
      );
    }
    console.warn("docs-site sync: vault PRDs skipped (requirements/ not mounted)");
    return;
  }

  rimrafGenerated("prd");
  const files = walkMd(vault);
  const indexRows = [];
  for (const abs of files) {
    const rel = path.relative(vault, abs).replace(/\\/g, "/");
    if (rel === "Products.md") continue;
    const raw = fs.readFileSync(abs, "utf8");
    const { fm, body } = parseFrontmatter(raw);
    const title = fm.title || path.basename(abs, ".md");
    const slug = slugify(path.basename(abs, ".md"));
    const converted = wikilinksToMd(body);
    writeGenerated(
      `prd/${slug}.md`,
      starlightPage({
        title,
        description: fm.title || title,
        body: converted,
        source: `Obsidian ${rel}`,
      }),
    );
    indexRows.push(`| ${title} | [open](/prd/${slug}/) | \`${rel}\` |`);
  }

  const products = path.join(vault, "Products.md");
  let catalogBody = "Product notes below are the **PRD corpus**.";
  if (fs.existsSync(products)) {
    catalogBody = wikilinksToMd(parseFrontmatter(fs.readFileSync(products, "utf8")).body);
  }

  writeGenerated(
    "prd/index.md",
    starlightPage({
      title: "PRDs (Obsidian)",
      description: "Product descriptions — the PRD corpus.",
      body: [catalogBody, "", "## Snapshot pages", "", "| Note | Site | Vault path |", "| --- | --- | --- |", ...indexRows.sort()].join(
        "\n",
      ),
      source: "Obsidian Projects/Destiny 2 Build Creator/",
    }),
  );
  console.log(`docs-site sync: ${files.length} PRD notes from ${vault}`);
}

copyLaw();
copyProduct();
copyOps();
copyPrds();
console.log("docs-site sync: ok");
