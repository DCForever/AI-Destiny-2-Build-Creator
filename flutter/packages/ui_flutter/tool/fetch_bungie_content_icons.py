#!/usr/bin/env python3
"""Download official Bungie CDN icons for offline Widgetbook / hosts.

Sources:
  - Paths in destiny_official_icons.dart + Next catalogFilterVisuals.ts (meta/frame)
  - Curated weapon item icons in EXTRA_WEAPON_ICONS (fixture catalog art)

Stores under assets/bungie-content/icons/ and regenerates
lib/src/bungie_content_local_assets.g.dart.

Usage (from packages/ui_flutter):
  python tool/fetch_bungie_content_icons.py
"""

