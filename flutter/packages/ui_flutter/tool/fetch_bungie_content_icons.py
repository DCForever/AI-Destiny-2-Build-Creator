BASE = "https://www.bungie.net"


def collect_paths() -> list[str]:
    paths: set[str] = set(EXTRA_WEAPON_ICONS)
    for src in (OFFICIAL_DART, WEB_FILTERS):
        if not src.is_file():
            continue
        text = src.read_text(encoding="utf-8")
        for m in re.finditer(
            r"/common/destiny2_content/icons/[A-Za-z0-9_.-]+\.(?:png|jpg|jpeg)",
            text,
        ):
            paths.add(m.group(0))
    return sorted(paths)


def download(path: str) -> bool:
    name = path.rsplit("/", 1)[-1]
    out = ICONS_DIR / name
    url = f"{BASE}{path}"
    try:
        with urllib.request.urlopen(url, timeout=30) as resp:
            data = resp.read()
        if len(data) < 200:
            print(f"  skip (too small) {name}")
            return False
        out.write_bytes(data)
        print(f"  ok {name} ({len(data)} bytes)")
        return True
    except Exception as e:  # noqa: BLE001
        print(f"  fail {name}: {e}")
        return False


def write_generated(basenames: list[str]) -> None:
    lines = [
        "// GENERATED by tool/fetch_bungie_content_icons.py — do not edit by hand.",
        "// ignore_for_file: lines_longer_than_80_chars",
        "",
        "/// Basenames under [kBungieContentAssetDir] that ship with this package.",
        "const Set<String> kBungieContentLocalBasenames = {",
    ]
    for b in basenames:
        lines.append(f"  '{b}',")
    lines += [
        "};",
        "",
    ]
    GEN.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {GEN.relative_to(ROOT)} ({len(basenames)} basenames)")


def main() -> None:
    ICONS_DIR.mkdir(parents=True, exist_ok=True)
    paths = collect_paths()
    print(f"fetching {len(paths)} CDN paths…")
    for p in paths:
        download(p)
    basenames = sorted(
        p.name
        for p in ICONS_DIR.iterdir()
        if p.suffix.lower() in {".png", ".jpg", ".jpeg"}
    )
    write_generated(basenames)
    print(f"done — {len(basenames)} local icons in {ICONS_DIR.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
